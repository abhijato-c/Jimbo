     inline Bitboard pdep(Bitboard val, Bitboard mask) {
          Bitboard res = 0;
          for (Bitboard m = mask; m; m &= (m - 1)) {
               Bitboard bit = m & -m; // Get lowest set bit of mask
               if (val & 1) res |= bit;
               val >>= 1;
          }
          return res;
     }
     inline Bitboard blsr(Bitboard val) { return val & (val - 1); }
